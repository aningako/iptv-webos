#!/usr/bin/env python3
"""Make the app's built-in channel list (app/com.homebrew.iptv/channels.m3u) from an M3U playlist.

Usage: python3 scripts/import_playlist.py playlist.m3u [more.m3u ...]   (streams already listed are skipped)

Streams that are unauthorized restreams of paid channels are left out (raw-IP capture devices, anonymous
domains, faked browser identities). Duplicate channels are kept as separate entries; the app merges them
into one channel with backup sources.
"""
import re, sys, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'app', 'com.homebrew.iptv', 'channels.m3u')
OUT_JS = os.path.join(ROOT, 'app', 'com.homebrew.iptv', 'channels.js')   # same list as a script (no file fetch needed)

# (reason, test on channel name + url)
EXCLUDE = [
    ('paid channel restreamed from a home capture device', lambda n, u: '125.227.210.55' in u),
    ('paid channel restreamed from a bare IP address', lambda n, u: '202.150.165.66' in u),
    ('paid sports channel on an anonymous domain', lambda n, u: 'adcdsd123321.shop' in u),
    ('paid channel that only plays with a faked browser identity', lambda n, u: n.startswith('AXN Asia Thailand')),
    ('free service reached with a faked US location (jmp2.uk)', lambda n, u: 'jmp2.uk/' in u),
    # checked on the TV 2026-11-21: these don't play there (region-locked, offline, or the TV's player refuses them)
    ('not available (region-locked from the Philippines)', lambda n, u: n.startswith('Animax Asia India')),
    ('not available (stream offline)', lambda n, u: n.startswith('CLTV 36')),
    ('not available (doesn\'t play on the TV)', lambda n, u: n.startswith('DUST') or n.startswith('CBS News')),
    ('paid news channel restreamed by an unauthorized OTT/IPTV service', lambda n, u: any(h in u for h in ('aynaott.com', 'antik.sk', 'freem3u.xyz', 'smartplaytv.in', 'ioapk.com'))),
]


def main(srcs):
    out, kept, dropped, urls = ['#EXTM3U'], 0, [], set()
    for src in srcs:
        kept += read(src, out, dropped, urls)
    write(out, kept, dropped)


def read(src, out, dropped, urls):
    lines = open(src, encoding='utf-8', errors='replace').read().splitlines()
    kept, i = 0, 0
    while i < len(lines):
        if lines[i].startswith('#EXTINF'):
            block = [lines[i]]
            j = i + 1
            while j < len(lines) and lines[j].startswith('#') and not lines[j].startswith('#EXTINF'):
                block.append(lines[j]); j += 1
            url = lines[j].strip() if j < len(lines) else ''
            name = lines[i].rsplit(',', 1)[-1].strip()
            why = next((r for r, test in EXCLUDE if test(name, url)), None)
            if why:
                dropped.append((name, why))
            elif url and url not in urls:
                urls.add(url); out += block + [url]; kept += 1
            i = j + 1
        else:
            i += 1
    return kept


LOGO_DIR = os.path.join(ROOT, 'app', 'com.homebrew.iptv', 'logos')


def bundle_logos(out):
    """Download every tvg-logo into app/.../logos/ and point the playlist at the local copy: some logo hosts
    (imgur) answer the TV's browser with 429, and local logos also show without internet."""
    import hashlib, urllib.request
    os.makedirs(LOGO_DIR, exist_ok=True)
    done, res = {}, []
    for line in out:
        m = re.search(r'tvg-logo="(https?://[^"]+)"', line)
        if m:
            url = m.group(1)
            if url not in done:
                ext = os.path.splitext(url.split('?')[0])[1].lower()
                ext = ext if ext in ('.png', '.jpg', '.jpeg', '.svg', '.webp', '.gif') else '.png'
                name = hashlib.sha1(url.encode()).hexdigest()[:12] + ext
                try:
                    req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0 (IPTV Player build script)'})
                    data = urllib.request.urlopen(req, timeout=20).read()
                    open(os.path.join(LOGO_DIR, name), 'wb').write(data)
                    done[url] = 'logos/' + name
                except Exception as e:
                    print('  logo not downloaded (%s): %s' % (e, url))
                    done[url] = url
            line = line.replace(url, done[url])
        res.append(line)
    print('  %d logos bundled in %s' % (sum(1 for v in done.values() if v.startswith('logos/')), LOGO_DIR))
    return res


def write(out, kept, dropped):
    out = bundle_logos(out)
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('\n'.join(out) + '\n')
    import json
    with open(OUT_JS, 'w', encoding='utf-8') as f:
        f.write('/* Built-in channels, generated by scripts/import_playlist.py */\nwindow.BUILTIN_M3U = ' + json.dumps('\n'.join(out) + '\n') + ';\n')
    print('kept %d streams -> %s' % (kept, OUT))
    for n, why in sorted(set(dropped)):
        print('  left out: %-28s (%s)' % (n, why))


if __name__ == '__main__':
    main(sys.argv[1:] or ['/mnt/c/Users/aning/Downloads/iptv-PH.m3u'])
